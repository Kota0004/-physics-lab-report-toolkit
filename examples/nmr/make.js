// 核磁気共鳴レポート(タイプ打ち部分)の生成スクリプト。
// lib/report.js のヘルパーを使い、build/nmr.docx を出力する。
//
//   node make.js
//
// 手書き(表紙+予習 −1−〜−4−+課題シート)が cover/cover.pdf。
// タイプ打ちはページ 5 から、式番号は手書き原理の (1)〜(12) に続けて (13) から。
// 課題は教科書 §4 ではなく配布資料「核磁気共鳴『§4.課題』」の課題(1)〜(3)に準拠。

const R = require("../../lib/report");
const { T, sub, sup, m, mfrac, msum, msub, msup, mbr } = R;

const HERE = __dirname;
const FIG = "figures";

// ---------- 測定データ(data/nmr_measurements.csv より)----------
const fMHz = ["8.0", "8.5", "9.0", "9.5", "10.0", "10.5", "11.0"];
const BmT = ["188.4", "200.2", "212.4", "224.0", "235.9", "248.0", "259.8"];

const t1 = [["周波数 f [MHz]", "磁場 B [mT]"]];
for (let i = 0; i < 7; i++) t1.push([fMHz[i], BmT[i]]);

// 最小二乗法の計算表(B̄ = 0.22410 T、f̄ = 9.5000×10⁶ Hz)
const t2 = [
  ["i", "1", "2", "3", "4", "5", "6", "7", "合計"],
  ["f [MHz]", "8.0", "8.5", "9.0", "9.5", "10.0", "10.5", "11.0", "—"],
  ["B [mT]", "188.4", "200.2", "212.4", "224.0", "235.9", "248.0", "259.8", "—"],
  ["B − B̄ [10⁻³ T]", "−35.7", "−23.9", "−11.7", "−0.1", "+11.8", "+23.9", "+35.7", "—"],
  ["f − f̄ [10⁶ Hz]", "−1.5", "−1.0", "−0.5", "0.0", "+0.5", "+1.0", "+1.5", "—"],
  ["(B − B̄)(f − f̄) [10³ T・Hz]", "53.55", "23.90", "5.85", "0.00", "5.90", "23.90", "53.55", "166.65"],
  ["(B − B̄)² [10⁻³ T²]", "1.2745", "0.5712", "0.1369", "0.0000", "0.1392", "0.5712", "1.2745", "3.9675"],
];

// ---------- 数式パーツ ----------
// MathRoundBrackets / MathSum は LibreOffice の OMML 変換で欠落する(□になる)ため、
// 括弧と Σ は通常文字で組む(Word のみで組む場合は mbr / msum に置き換えてよい)。
const devB = () => [m("("), msub([m("B")], [m("i")]), m(" − B̄)")];
const devF = () => [m("("), msub([m("f")], [m("i")]), m(" − f̄)")];

// ---------- 本文 ----------
const r = R.createReport({ assetDir: HERE });

r.head1("実験結果");
r.body([
  T("NMR 実験装置(静磁場を作る電磁石、静磁場と同方向の変調磁場を作る変調コイル、試料の周りに巻かれたコイル(プローブ)、高周波発振器(7.5〜12.5 MHz)、高周波ブリッジ回路)とデジタルオシロスコープを用い、硫酸銅(CuSO"),
  sub("4"), T(")水溶液中の H 原子核の核磁気共鳴信号を観測した。検出は磁場変調方式であり、オシロスコープを X–Y ポジションとして X 軸に磁場に比例した信号([MOD.CONT.] 最大で振幅 1 mT)、Y 軸に吸収信号を表示し、画面上の吸収曲線の中心に対応する磁場読み値を共鳴磁場 B とした。"),
]);
r.body([
  T("発振周波数 f を 8.0 MHz から 11.0 MHz まで 0.5 MHz 刻みの 7 点に設定し(手順では 12.5 MHz までの予定だったが、実験では 11.0 MHz までを測定した)、各周波数で [FIELD.ADJ.] により磁場強度を調整して H 原子核の NMR 信号を探し、共鳴磁場を記録した。結果を表1に示す。"),
]);
r.table("表1 核磁気共鳴が観測された周波数と磁場", [2200, 2200], t1);

r.head1("課題");
r.body([
  T("以下、配布資料 [2] の課題(1)〜(3)(教科書 §4 の課題から変更されたもの)に沿って解答する。数値計算は途中で丸めずに行い、最終結果のみを有効数字 5 桁に丸めた。"),
]);

r.head2("課題(1) 周波数の磁場依存性 df/dB");
r.body([
  T("表1の実験値について、周波数を [MHz] → [Hz](1 MHz = 1 × 10"), sup("6"),
  T(" Hz)、磁場を [mT] → [T](1 mT = 1 × 10"), sup("−3"),
  T(" T)に単位変換した。周波数 f を縦軸、磁場 B を横軸にとってプロットしたものを図1に示す。7 点は原点方向に向かう 1 本の直線上にほぼ完全に乗っており、共鳴条件(手書き原理の式(7)、ω = γ"),
  sub("n"), T("B"), sub("0"), T(")が示す f ∝ B の比例関係と整合する。"),
]);
r.figure(`${FIG}/fig1_f_vs_B.png`, 480, 320,
  "図1 H 原子核の NMR 共鳴周波数 f と共鳴磁場 B の関係。直線は式(13)の傾きをもつ最小二乗直線。",
  "共鳴周波数の磁場依存性");
r.body([
  T("周波数の磁場依存性 df/dB [Hz/T] は、配布資料 [2] に与えられた最小二乗法の式"),
]);
r.meqn([
  mfrac([m("df")], [m("dB")]),
  m(" = "),
  mfrac(
    [m("Σ "), ...devB(), ...devF()],
    [m("Σ ("), msub([m("B")], [m("i")]), m(" − B̄"), msup([m(")")], [m("2")])]
  ),
], 13);
r.body([
  T("により求めた。ここで B"), sub("i"), T("、f"), sub("i"), T(" は i 番目の磁場 [T]・周波数 [Hz]、B̄、f̄ は N = 7 個の磁場・周波数の平均であり、B̄ = 0.22410 T、f̄ = 9.5000 × 10"),
  sup("6"), T(" Hz である。式(13)の各項の計算を表2に整理する(合計の計算のみに表計算ソフトを用いた)。"),
]);
r.table("表2 最小二乗法の計算表", [2600, 700, 700, 700, 700, 700, 700, 700, 850], t2, 18);
r.body([T("表2の合計値を式(13)に代入すると")]);
r.meqn([
  mfrac([m("df")], [m("dB")]),
  m(" = "),
  mfrac(
    [m("1.6665 × "), msup([m("10")], [m("5")]), m(" T・Hz")],
    [m("3.9675 × "), msup([m("10")], [m("−3")]), m(" "), msup([m("T")], [m("2")])]
  ),
  m(" = 4.2003 × "), msup([m("10")], [m("7")]), m(" Hz/T"),
], 14);
r.body([
  T("を得る。よって求める周波数の磁場依存性は df/dB = "),
  T("4.2003 × 10", { bold: true }), sup("7", { bold: true }), T(" Hz/T", { bold: true }),
  T("(有効数字 5 桁)である。なお、このフィットの相関係数は r"), sup("2"),
  T(" = 0.99998 であり、切片(f̄ − (df/dB)B̄)は 8.7 × 10"), sup("4"),
  T(" Hz(0.087 MHz)と測定周波数に比べて十分小さく、直線性・比例性ともに極めて良い。"),
]);

r.head2("課題(2) ¹H の磁気回転比 γn");
r.body([
  T("共鳴条件 ω = γ"), sub("n"), T("B"), sub("0"), T("(手書き原理の式(7))と ω = 2πf より f = (γ"),
  sub("n"), T("/2π)B であるから、γ"), sub("n"), T(" は課題(1)で求めた df/dB を用いて γ"),
  sub("n"), T(" = 2π × df/dB で求められる。"),
]);
r.eqn([
  T("γ"), sub("n"), T(" = 2π × df/dB = 2π × 4.2003 × 10"), sup("7"), T(" = "),
  T("2.6391 × 10", { bold: true }), sup("8", { bold: true }), T(" s", { bold: true }),
  sup("−1", { bold: true }), T("・T", { bold: true }), sup("−1", { bold: true }),
], 15);
r.body([
  T("教科書 297 ページ表 1 に記された "), sup("1"), T("H の磁気回転比の理想値 γ"), sub("n"),
  T(" = 2.6752 × 10"), sup("8"), T(" s"), sup("−1"), T("・T"), sup("−1"),
  T(" と比較すると、実験値と理想値の比は 2.6391/2.6752 = 0.98652 であり、実験値は理想値より約 1.35 % 小さい。このずれについては考察 1 で検討する。"),
]);

r.head2("課題(3) ¹H の g 因子 gn");
r.body([
  T("磁気モーメントの定義(手書き原理の式(2)、μ = γ"), sub("n"), T("ħI = g"), sub("n"),
  T("μ"), sub("N"), T("I)より γ"), sub("n"), T("ħ = g"), sub("n"), T("μ"), sub("N"),
  T(" であるから、g 因子は g"), sub("n"), T(" = γ"), sub("n"), T("ħ/μ"), sub("N"),
  T(" で求められる。核ボーア磁子数は教科書 297 ページに記された値 μ"), sub("N"),
  T(" = 5.0508 × 10"), sup("−27"),
  T(" J/T を、プランク定数は教科書巻末に記された値 h = 6.626 × 10"), sup("−34"),
  T(" J・s を用い、ħ = h/2π = 1.0546 × 10"), sup("−34"), T(" J・s とした。課題(2)で求めた γ"),
  sub("n"), T(" を代入すると"),
]);
r.eqn([
  T("g"), sub("n"), T(" = γ"), sub("n"), T("ħ/μ"), sub("N"),
  T(" = (2.6391 × 10"), sup("8"), T(" × 1.0546 × 10"), sup("−34"), T(")/(5.0508 × 10"), sup("−27"),
  T(") = "), T("5.5103", { bold: true }),
], 16);
r.body([
  T("を得る(途中を丸めない値で計算し、最終結果のみを有効数字 5 桁に丸めた)。教科書 297 ページ表 1 に記された "),
  sup("1"), T("H の g 因子の理想値 g"), sub("n"),
  T(" = 5.58554 と比較すると、比は 5.5103/5.58554 = 0.98653 であり、γ"), sub("n"),
  T(" と同じく約 1.35 % 小さい。g"), sub("n"), T(" は γ"), sub("n"),
  T(" に比例するため(g"), sub("n"), T(" = γ"), sub("n"), T("ħ/μ"), sub("N"),
  T("、ħ と μ"), sub("N"), T(" は定数)、ずれの原因は課題(2)と共通である。"),
]);

r.head1("考察");

r.head2("1.理想値との系統的なずれについて");
r.body([
  T("得られた γ"), sub("n"), T("・g"), sub("n"),
  T(" はいずれも理想値より約 1.35 % 小さかった。まず統計的なばらつきの可能性を検討する。図1のとおり 7 点は r"),
  sup("2"), T(" = 0.99998 で直線に乗っており、傾きの相対標準誤差は約 0.2 % と見積もられる。したがって 1.35 % のずれは測定のばらつきでは説明できず、系統的な誤差である。"),
]);
r.body([
  T("f = (γ"), sub("n"), T("/2π)B の傾きが一様に小さく観測されたことは、記録した磁場読み値 B が試料位置の真の磁場より一様に約 1.4 % 大きく表示されていたと考えれば説明できる。本実験の磁場値は装置の磁場モニタの表示値であり、磁場を測る素子の較正誤差のほか、電磁石磁場の空間的不均一性やヒステリシスのために、試料(プローブ先端)位置の磁場と磁場測定点の磁場がずれていた可能性がある。また、切片 0.087 MHz は磁場に換算して約 2 mT のゼロ点オフセットに相当し、これも磁場表示の較正誤差と整合的である。一方、試料内部の局所磁場や化学シフトによる共鳴点のずれ(教科書 301〜302 ページ)は ppm のオーダーであり、1 % を超える本実験のずれの説明にはならない。"),
]);

r.head2("2.共鳴磁場の読み取り精度について");
r.body([
  T("磁場変調の振幅は最大で 1 mT であり、吸収曲線の中心(共鳴磁場)の読み取りには ±1 mT 程度(磁場の 0.5 % 程度)の不確かさが入り得る。これは各点で独立なランダム誤差であり、最小二乗法により 7 点で平均化されるため、傾き df/dB への寄与は上記の 0.2 % 程度に抑えられている。有効数字 5 桁で結果を表示したが、実際の確度は考察 1 の磁場較正の系統誤差(〜1 %)に制限されている点に注意が必要である。"),
]);

r.head2("3.試料に CuSO₄ 水溶液を用いる理由について");
r.body([
  T("信号源は水(H"), sub("2"), T("O)中の "), sup("1"),
  T("H 核である。O の原子核は陽子 8 個・中性子 8 個の偶々核でスピンをもたず、核磁気共鳴に寄与しない。純水では緩和時間 T"),
  sub("1"), T(" が長く、電磁波の吸収により 2 準位の占有数差がなくなって吸収が飽和してしまう。常磁性イオン Cu"),
  sup("2+"), T(" を溶かすことでスピン–格子緩和が促進されて T"), sub("1"),
  T(" が短くなり、定常的なエネルギー吸収が起こるため、吸収信号を安定に観測できる(教科書 308 ページ)。"),
]);

r.raw(new (require("docx").Paragraph)({
  children: [new (require("docx").TextRun)({ text: "参考文献", font: R.GFONT, size: 26, bold: true })],
  spacing: { before: 240, after: 140 }, keepNext: true,
}));
