// 核磁気共鳴レポート(タイプ打ち部分)の生成スクリプト。
// lib/report.js のヘルパーを使い、build/nmr.docx を出力する。
//
//   node make.js
//
// 手書き(表紙+予習 −1−〜−4−+課題シート −5−)が cover/cover.pdf。
// タイプ打ちはページ 6 から、式番号は手書き原理の (1)〜(12) に続けて (13) から。
// 課題は教科書 §4 ではなく配布資料「核磁気共鳴『§4.課題』」の課題(1)〜(3)に準拠。
// 体裁指定: 実験結果・図・表は載せず、値の導出はすべて式で示す。参考文献欄なし。
// 分数はすべて Word 数式(mfrac)で視覚的な分数として組む。
// 数値の列挙は両端揃えの本文に入れると字間が伸びるため、式の行に置く。

const R = require("../../lib/report");
const { T, sub, sup, m, mfrac, msub, msup } = R;
const { Math: OMath } = require("docx");

const HERE = __dirname;

// ---------- 数式パーツ ----------
// MathRoundBrackets / MathSum は LibreOffice の OMML 変換で欠落する(□になる)ため、
// 括弧と Σ は通常文字で組む(Word のみで組む場合は mbr / msum に置き換えてよい)。
const omath = (children) => new OMath({ children });
const devB = () => [m("("), msub([m("B")], [m("i")]), m(" − B̄)")];
const devF = () => [m("("), msub([m("f")], [m("i")]), m(" − f̄)")];

// ---------- 本文 ----------
const r = R.createReport({ assetDir: HERE });

r.head1("課題");
r.body([
  T("以下、配布資料「核磁気共鳴『§4.課題』」の課題(1)〜(3)(教科書 §4 の課題から変更されたもの)に沿って解答する。用いる実験値は、課題シート(−5− ページ)の表に記入した、核磁気共鳴が観測された周波数 f [MHz] と磁場 B [mT] の 7 組(N = 7)である。"),
]);

r.head2("課題(1) 周波数の磁場依存性 df/dB");
r.body([
  T("実験値を、周波数は 1 MHz = 1 × 10"), sup("6"), T(" Hz により [MHz] → [Hz] に、磁場は 1 mT = 1 × 10"),
  sup("−3"), T(" T により [mT] → [T] に単位変換して用いる。まず磁場と周波数の平均 B̄、f̄ を求めると"),
]);
r.meqn([
  m("B̄ = "),
  mfrac(
    [m("0.1884+0.2002+0.2124+0.2240+0.2359+0.2480+0.2598")],
    [m("7")]
  ),
  m(" = 0.22410 T"),
], 13);
r.meqn([
  m("f̄ = "),
  mfrac(
    [m("8.0+8.5+9.0+9.5+10.0+10.5+11.0")],
    [m("7")]
  ),
  m(" × "), msup([m("10")], [m("6")]),
  m(" = 9.5000 × "), msup([m("10")], [m("6")]), m(" Hz"),
], 14);
r.body([
  T("である。周波数の磁場依存性 df/dB [Hz/T] は、配布資料に与えられた最小二乗法の式"),
]);
r.meqn([
  mfrac([m("df")], [m("dB")]),
  m(" = "),
  mfrac(
    [m("Σ "), ...devB(), ...devF()],
    [m("Σ ("), msub([m("B")], [m("i")]), m(" − B̄"), msup([m(")")], [m("2")])]
  ),
], 15);
r.body([T("により求める。各測定値の偏差はそれぞれ")]);
r.eqn([
  T("B"), sub("i"), T(" − B̄ = −35.7、−23.9、−11.7、−0.1、+11.8、+23.9、+35.7 (× 10"), sup("−3"), T(" T)"),
], 16);
r.eqn([
  T("f"), sub("i"), T(" − f̄ = −1.5、−1.0、−0.5、0.0、+0.5、+1.0、+1.5 (× 10"), sup("6"), T(" Hz)"),
], 17);
r.body([T("であるから、式(15)の分子・分母の和はそれぞれ")]);
r.eqn([
  T("Σ(B"), sub("i"), T("−B̄)(f"), sub("i"), T("−f̄) = (53.55+23.90+5.85+0.00+5.90+23.90+53.55) × 10"),
  sup("3"), T(" = 1.6665 × 10"), sup("5"), T(" T・Hz"),
], 18);
r.eqn([
  T("Σ(B"), sub("i"), T("−B̄)"), sup("2"), T(" = (1274.49+571.21+136.89+0.01+139.24+571.21+1274.49) × 10"),
  sup("−6"), T(" = 3.96754 × 10"), sup("−3"), T(" T"), sup("2"),
], 19);
r.body([T("と計算される。これらを式(15)に代入すると")]);
r.meqn([
  mfrac([m("df")], [m("dB")]),
  m(" = "),
  mfrac(
    [m("1.6665 × "), msup([m("10")], [m("5")]), m(" T・Hz")],
    [m("3.96754 × "), msup([m("10")], [m("−3")]), m(" "), msup([m("T")], [m("2")])]
  ),
  m(" = 4.2003 × "), msup([m("10")], [m("7")]), m(" Hz/T"),
], 20);
r.body([
  T("を得る。よって求める周波数の磁場依存性は df/dB = "),
  T("4.2003 × 10", { bold: true }), sup("7", { bold: true }), T(" Hz/T", { bold: true }),
  T("(有効数字 5 桁)である。"),
]);

r.head2("課題(2) ¹H の磁気回転比 γn");
r.body([
  T("共鳴条件 ω = γ"), sub("n"), T("B"), sub("0"), T("(手書き原理の式(7))と ω = 2πf より f = (γ"),
  sub("n"), T("/2π)B であるから、磁気回転比は γ"), sub("n"),
  T(" = 2π × df/dB で求められる。課題(1)の結果を代入すると"),
]);
r.eqn([
  omath([
    msub([m("γ")], [m("n")]),
    m(" = 2π × "),
    mfrac([m("df")], [m("dB")]),
    m(" = 2π × 4.2003 × "), msup([m("10")], [m("7")]),
  ]),
  T(" = "),
  T("2.6391 × 10", { bold: true }), sup("8", { bold: true }), T(" s", { bold: true }),
  sup("−1", { bold: true }), T("・T", { bold: true }), sup("−1", { bold: true }),
], 21);
r.body([
  T("を得る(有効数字 5 桁)。教科書 297 ページ表 1 に記された "), sup("1"),
  T("H の磁気回転比の理想値 γ"), sub("n"), T(" = 2.6752 × 10"), sup("8"), T(" s"), sup("−1"),
  T("・T"), sup("−1"), T(" と比較すると、その比は"),
]);
r.eqn([
  omath([
    mfrac(
      [m("2.6391 × "), msup([m("10")], [m("8")])],
      [m("2.6752 × "), msup([m("10")], [m("8")])]
    ),
  ]),
  T(" = 0.98651"),
], 22);
r.body([
  T("であり、実験値は理想値より約 1.35 % 小さい。このずれについては考察 1 で検討する。"),
]);

r.head2("課題(3) ¹H の g 因子 gn");
r.body([
  T("磁気モーメントの定義(手書き原理の式(2)、μ = γ"), sub("n"), T("ħI = g"), sub("n"),
  T("μ"), sub("N"), T("I)より γ"), sub("n"), T("ħ = g"), sub("n"), T("μ"), sub("N"),
  T(" であるから、g 因子は g"), sub("n"), T(" = γ"), sub("n"), T("ħ/μ"), sub("N"),
  T(" で求められる。核ボーア磁子数は教科書 297 ページに記された値 μ"), sub("N"),
  T(" = 5.0508 × 10"), sup("−27"),
  T(" J/T を、プランク定数は教科書巻末に記された値 h = 6.626 × 10"), sup("−34"),
  T(" J・s を用いる。まず ħ は"),
]);
r.eqn([
  omath([
    m("ħ = "),
    mfrac([m("h")], [m("2π")]),
    m(" = "),
    mfrac([m("6.626 × "), msup([m("10")], [m("−34")])], [m("2π")]),
    m(" = 1.0546 × "), msup([m("10")], [m("−34")]),
  ]),
  T(" J・s"),
], 23);
r.body([T("であり、課題(2)で求めた γ"), sub("n"), T(" を代入すると")]);
r.eqn([
  omath([
    msub([m("g")], [m("n")]),
    m(" = "),
    mfrac([msub([m("γ")], [m("n")]), m("ħ")], [msub([m("μ")], [m("N")])]),
    m(" = "),
    mfrac(
      [m("2.6391 × "), msup([m("10")], [m("8")]), m(" × 1.0546 × "), msup([m("10")], [m("−34")])],
      [m("5.0508 × "), msup([m("10")], [m("−27")])]
    ),
  ]),
  T(" = "),
  T("5.5104", { bold: true }),
], 24);
r.body([
  T("を得る(有効数字 5 桁)。教科書 297 ページ表 1 に記された "), sup("1"),
  T("H の g 因子の理想値 g"), sub("n"), T(" = 5.58554 と比較すると、その比は"),
]);
r.eqn([
  omath([
    mfrac([m("5.5104")], [m("5.58554")]),
  ]),
  T(" = 0.98655"),
], 25);
r.body([
  T("であり、γ"), sub("n"), T(" と同じく約 1.35 % 小さい。g"), sub("n"), T(" は γ"), sub("n"),
  T(" に比例するため(g"), sub("n"), T(" = γ"), sub("n"), T("ħ/μ"), sub("N"),
  T("、ħ と μ"), sub("N"), T(" は定数)、ずれの原因は課題(2)と共通である。"),
]);

r.head1("考察");

r.head2("1.理想値との系統的なずれについて");
r.body([
  T("得られた γ"), sub("n"), T("・g"), sub("n"),
  T(" はいずれも理想値より約 1.35 % 小さかった。まず統計的なばらつきの可能性を検討する。7 点の測定値は f = (γ"),
  sub("n"), T("/2π)B の直線関係に極めてよく従っており、最小二乗フィットの相関係数は r"),
  sup("2"), T(" = 0.99998、傾き df/dB の相対標準誤差は約 0.2 % と見積もられる。したがって 1.35 % のずれは測定のばらつきでは説明できず、系統的な誤差である。"),
]);
r.body([
  T("f = (γ"), sub("n"), T("/2π)B の傾きが一様に小さく観測されたことは、記録した磁場読み値 B が試料位置の真の磁場より一様に約 1.4 % 大きく表示されていたと考えれば説明できる。本実験の磁場値は装置の磁場モニタの表示値であり、磁場を測る素子の較正誤差のほか、電磁石磁場の空間的不均一性やヒステリシスのために、試料(プローブ先端)位置の磁場と磁場測定点の磁場がずれていた可能性がある。また、直線の切片 f̄ − (df/dB)B̄ = 8.7 × 10"),
  sup("4"),
  T(" Hz(0.087 MHz)は磁場に換算して約 2 mT のゼロ点オフセットに相当し、これも磁場表示の較正誤差と整合的である。一方、試料内部の局所磁場や化学シフトによる共鳴点のずれ(教科書 301〜302 ページ)は ppm のオーダーであり、1 % を超える本実験のずれの説明にはならない。"),
]);

r.head2("2.共鳴磁場の読み取り精度について");
r.body([
  T("磁場変調の振幅は最大で 1 mT であり、吸収曲線の中心(共鳴磁場)の読み取りには ±1 mT 程度(磁場の 0.5 % 程度)の不確かさが入り得る。これは各点で独立なランダム誤差であり、最小二乗法により 7 点で平均化されるため、傾き df/dB への寄与は上記の 0.2 % 程度に抑えられている。有効数字 5 桁で結果を表示したが、実際の確度は考察 1 の磁場較正の系統誤差(〜1 %)に制限されている点に注意が必要である。"),
]);

r.head2("3.試料に CuSO₄ 水溶液を用いる理由について");
r.body([
  T("信号源は水(H"), sub("2"), T("O)中の "), sup("1"),
  T("H 核である。O の原子核は陽子 8 個・中性子 8 個の偶々核でスピンをもたず、核磁気共鳴に寄与しない。純水では緩和時間 T"),
  sub("1"), T(" が長く、電磁波の吸収により 2 準位の占有数差がなくなって吸収が飽和してしまう。常磁性イオン Cu"),
  sup("2+"), T(" を溶かすことでスピン–格子緩和が促進されて T"), sub("1"),
  T(" が短くなり、定常的なエネルギー吸収が起こるため、吸収信号を安定に観測できる(教科書 308 ページ)。"),
]);

